import { GenerateInput } from '@/lib/validations'

export function buildStoriesPrompt(input: GenerateInput): string {
  const goalMap = {
    dm: 'написать в Direct',
    telegram: 'подписаться на Telegram',
    call: 'записаться на звонок',
    landing: 'перейти по ссылке',
  }

  const voiceLine = input.brand_voice
    ? `- Голос бренда: ${input.brand_voice}`
    : `- Тон: ${input.tone}`

  return `Ты — архитектор Stories для Instagram, создающий серии из 5 слайдов с нарративным давлением для конверсии.

КОНТЕКСТ:
- Ниша: ${input.niche}
- Оффер: ${input.offer}
- Целевая аудитория: ${input.audience}
- Ключевые боли: ${input.pain_points}
${voiceLine}
- Цель: ${goalMap[input.conversion_goal]}

СОЗДАЙ 5 СЛАЙДОВ:
Слайд 1 — ХУК: Прерыватель паттерна. Смелое утверждение, которое заставит тапнуть дальше
Слайд 2 — ПРОБЛЕМА: Назови их точную боль. Заставь почувствовать себя понятыми
Слайд 3 — ИНСАЙТ: Один мощный рефрейм или истина, меняющая точку зрения
Слайд 4 — РЕШЕНИЕ: Как твой оффер конкретно решает это. Без воды — конкретика
Слайд 5 — CTA: Срочность + принудительное действие. Упомяни опрос, ссылку или триггер для DM

ПРАВИЛА:
- Каждый слайд максимум 3 строки (Stories — визуальный формат)
- Используй срочность без фальши
- Заканчивай ЖЁСТКИМ CTA — никаких пассивных намёков

ВАЖНО: Весь текст пиши ТОЛЬКО на русском языке. Никакого английского.

Верни ТОЛЬКО JSON-массив ровно из 5 строк:
["текст слайда 1", "текст слайда 2", "текст слайда 3", "текст слайда 4", "текст слайда 5"]`
}
