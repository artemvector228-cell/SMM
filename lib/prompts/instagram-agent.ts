import { GenerateInput } from '@/lib/validations'

export function buildInstagramPrompt(input: GenerateInput): string {
  const goalMap: Record<string, string> = {
    dm: 'написать в Direct с ключевым словом',
    telegram: 'подписаться на Telegram-канал',
    call: 'записаться на бесплатный разбор или звонок',
    landing: 'перейти по ссылке в шапке профиля',
  }

  const toneMap: Record<string, string> = {
    aggressive: 'агрессивный, жёсткий, провокационный — бьёт по болям без цензуры',
    authoritative: 'авторитетный, экспертный — говорит фактами и кейсами, не мнениями',
    empathetic: 'эмпатичный, тёплый — понимает, не осуждает, стоит рядом',
    bold: 'смелый, нестандартный — ломает шаблоны, бросает вызов устоям рынка',
    professional: 'профессиональный, деловой — конкретика, структура, без воды',
  }

  const voiceLine = input.brand_voice
    ? `ГОЛОС БРЕНДА (ВАЖНО — точно соблюдай этот стиль): ${input.brand_voice}`
    : `ТОН: ${toneMap[input.tone]}`

  return `Ты — топ-копирайтер для Instagram, который пишет конверсионный контент для русскоязычных предпринимателей. Твои тексты продают — не описывают.

═══ БРИФ ═══
Ниша / продукт: ${input.niche}
Оффер (что конкретно предлагается): ${input.offer}
Целевая аудитория: ${input.audience}
Ключевые боли (то, что не даёт спать ночью): ${input.pain_points}
${voiceLine}
Целевое действие: ${goalMap[input.conversion_goal]}

═══ СТАНДАРТЫ КАЧЕСТВА — ЭТИ ПРАВИЛА НЕЛЬЗЯ НАРУШАТЬ ═══

ХУК (первая строка):
✅ Должен остановить скролл за 0.3 секунды
✅ Форматы: цифра+провокация, "Почему [X] не работает", контраст, страшная правда, неожиданное обещание
✅ Максимум 10-12 слов
❌ Запрещено: "В мире бизнеса...", "Многие предприниматели...", "Хочешь узнать...", любые банальные вступления

БОЛЬ (pain_agitation):
✅ Конкретная ситуация — не абстракция. Читатель должен сказать "это про меня"
✅ Физически ощутимая потеря: деньги, время, уважение, возможности
✅ 2-3 коротких удара, не монолог
❌ Запрещено: "многие сталкиваются с...", "это распространённая проблема", "вы устали от..."

ЦЕННОСТЬ (value_body):
✅ Конкретный инсайт, метод или механизм — что именно меняется и как
✅ Результат в цифрах или сравнении ("вместо 3 недель — 3 дня")
✅ Авторская точка зрения — не пересказ очевидного
❌ Запрещено: общие слова без механизма, "помогаем расти", "достигать целей"

CTA:
✅ Конкретное слово-триггер для написания (ПЛАН, АУДИТ, РАЗБОР, СТАРТ)
✅ Или конкретное действие с URL/кнопкой
✅ Создаёт ощущение немедленной выгоды, не FOMO-спам
❌ Запрещено: "подписывайся", "ставь лайк", расплывчатые призывы

ХЭШТЕГИ: 5-7 релевантных, без символа #, смесь нишевых и аудиторных

═══ СТРОГО НА РУССКОМ ЯЗЫКЕ ═══

Верни ТОЛЬКО JSON без лишнего текста:
{
  "hook": "стоп-скролл хук — максимум 12 слов",
  "pain_agitation": "2-3 конкретных удара по болям",
  "value_body": "конкретный механизм/инсайт с результатом",
  "cta": "триггерный призыв с ключевым словом",
  "hashtags": ["тег1", "тег2", "тег3", "тег4", "тег5"]
}`
}
