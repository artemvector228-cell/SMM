import { GenerateInput } from '@/lib/validations'

export function buildReelsPrompt(input: GenerateInput): string {
  const goalMap = {
    dm: 'написать в Direct с ключевым словом',
    telegram: 'подписаться на Telegram',
    call: 'записаться на звонок',
    landing: 'перейти по ссылке в шапке профиля',
  }

  const voiceLine = input.brand_voice
    ? `- Голос бренда: ${input.brand_voice}`
    : `- Тон: ${input.tone}`

  return `Ты — сценарист Reels, специализирующийся на коротких конверсионных видео для русскоязычной аудитории.

КОНТЕКСТ:
- Ниша: ${input.niche}
- Оффер: ${input.offer}
- Целевая аудитория: ${input.audience}
- Ключевые боли: ${input.pain_points}
${voiceLine}
- Цель: ${goalMap[input.conversion_goal]}

СТРУКТУРА СЦЕНАРИЯ (30 секунд):
- Хук (0–3 сек): Одна взрывная фраза в камеру ИЛИ жирный текстовый оверлей
- Сцена 1 (3–10 сек): Визуально и словесно обозначь проблему
- Сцена 2 (10–20 сек): Инсайт / ценность / метод
- Сцена 3 (20–27 сек): Результат или доказательство
- CTA (27–30 сек): Принудительное действие с ключевым словом

ПРАВИЛА:
- Хук должен вызвать любопытство или страх упустить
- Пиши сцены как разговорный сценарий (живой, чёткий язык)
- CTA должен содержать ключевое слово (например: «Напишите ПЛАН», «Комментируйте АУДИТ»)

ВАЖНО: Весь текст пиши ТОЛЬКО на русском языке. Никакого английского.

Верни ТОЛЬКО этот JSON:
{
  "hook": "фраза-хук в начале видео",
  "scenes": [
    "сценарий сцены 1 (проблема)",
    "сценарий сцены 2 (инсайт)",
    "сценарий сцены 3 (результат)"
  ],
  "cta": "финальный призыв к действию с ключевым словом"
}`
}
