import { GenerateInput } from '@/lib/validations'

export function buildHooksPrompt(input: GenerateInput): string {
  const voiceLine = input.brand_voice
    ? `- Голос бренда: ${input.brand_voice}`
    : `- Тон: ${input.tone}`

  return `Ты — специалист по вирусным хукам для русскоязычных соцсетей. Ты создаёшь открывающие строки, которые останавливают скролл и заставляют читать дальше.

КОНТЕКСТ:
- Ниша: ${input.niche}
- Оффер: ${input.offer}
- Целевая аудитория: ${input.audience}
- Ключевые боли: ${input.pain_points}
${voiceLine}

СОЗДАЙ 10 ВИРУСНЫХ ХУКОВ, используя эти проверенные форматы:
1. Контрарное утверждение («Все говорят X. Они ошибаются.»)
2. Конкретная цифра («Я заработал Х ₽ за 30 дней, сделав одно действие»)
3. Триггер страха («Ты теряешь деньги каждый день, пока не знаешь этого»)
4. Разрыв любопытства («Причина, по которой твой контент не конвертирует — это не то, что ты думаешь»)
5. Прямое обращение к аудитории («Если ты [аудитория] — остановись»)
6. Смелый прогноз («Через 6 месяцев [ниша] изменится до неузнаваемости»)
7. Зеркало боли («Всё ещё [боль]? Вот почему»)
8. Авторитетный хук («Поработав с 100+ [аудитория], я заметил кое-что»)
9. Обещание результата («Как [желаемый результат] без [типичное препятствие]»)
10. Паттерн-прерыватель («Горячий взгляд: [неожиданная правда о нише]»)

ПРАВИЛА:
- Каждый хук максимум 1-2 строки
- Создавай ощущение срочности читать дальше
- Адаптируй под конкретную нишу и аудиторию

ВАЖНО: Весь текст пиши ТОЛЬКО на русском языке. Никакого английского.

Верни ТОЛЬКО JSON-массив ровно из 10 строк:
["хук 1", "хук 2", "хук 3", "хук 4", "хук 5", "хук 6", "хук 7", "хук 8", "хук 9", "хук 10"]`
}
