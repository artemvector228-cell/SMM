import { GenerateInput } from '@/lib/validations'

export function buildHooksPrompt(input: GenerateInput): string {
  const voiceLine = input.brand_voice
    ? `Голос бренда: ${input.brand_voice}`
    : `Тон: ${input.tone}`

  return `Ты — специалист по стоп-скролл хукам для русскоязычного контента. Твои хуки заставляют людей остановиться и прочитать. Каждый хук — отдельная психологическая стратегия.

═══ КОНТЕКСТ ═══
Ниша: ${input.niche}
Оффер: ${input.offer}
Аудитория: ${input.audience}
Боли: ${input.pain_points}
${voiceLine}

═══ ТРЕБОВАНИЯ ═══
Создай ровно 10 хуков — по одному на каждый из форматов ниже.
Каждый хук — максимум 12-15 слов. Конкретно. Провокационно. Без воды.

ФОРМАТЫ (строго по порядку):
1. КОНТРАРНЫЙ — противоречит общепринятому мнению в нише
2. ЧИСЛО + РЕЗУЛЬТАТ — конкретная цифра + неожиданный исход
3. СТРАХ УПУСТИТЬ — то, что уже происходит без их участия
4. РАЗРЫВ ОЖИДАНИЙ — читатель ожидает одно, получает другое
5. ПРЯМОЙ — честно и жёстко называет проблему
6. ПРОРОЧЕСТВО — что будет через 6-12 месяцев без изменений
7. ЗЕРКАЛО — читатель узнаёт себя в описанной ситуации
8. АВТОРИТЕТ + ИНСАЙТ — экспертная позиция + неожиданный вывод
9. ОБЕЩАНИЕ ТРАНСФОРМАЦИИ — конкретный переход ДО → ПОСЛЕ
10. ПАТТЕРН-ПРЕРЫВАТЕЛЬ — нестандартное начало, рвёт шаблон

═══ ЗАПРЕЩЕНО ═══
❌ "Хочешь узнать как...", "Многие не знают, что...", "Это изменит твою жизнь"
❌ Клише и банальные фразы
❌ Повторять одну и ту же структуру
❌ Английские слова

СТРОГО НА РУССКОМ ЯЗЫКЕ.

Верни ТОЛЬКО JSON с массивом (каждый элемент = хук одного формата):
{"result": ["хук1", "хук2", "хук3", "хук4", "хук5", "хук6", "хук7", "хук8", "хук9", "хук10"]}`
}
