import { GenerateInput } from '@/lib/validations'

export function buildTelegramPrompt(input: GenerateInput): string {
  const goalMap = {
    dm: 'написать личное сообщение',
    telegram: 'подписаться на канал',
    call: 'записаться на звонок',
    landing: 'перейти по ссылке',
  }

  const voiceLine = input.brand_voice
    ? `- Голос бренда: ${input.brand_voice}`
    : `- Тон: ${input.tone}`

  return `Ты — стратег контента для Telegram, который строит доверие и экспертность так, чтобы читатели сами хотели обратиться.

КОНТЕКСТ:
- Ниша: ${input.niche}
- Оффер: ${input.offer}
- Целевая аудитория: ${input.audience}
- Ключевые боли: ${input.pain_points}
${voiceLine}
- Цель: ${goalMap[input.conversion_goal]}

СТРУКТУРА ПОСТА (5 блоков):
1. Хук — смелое утверждение или инсайт, создающий любопытство
2. Проблема — точная формулировка их боли на их языке, чтобы они почувствовали себя понятыми
3. Глубокая ценность — конкретный фреймворк, метод или истина, которую они ещё не слышали
4. Позиционирование — ненавязчивое подтверждение экспертности: результат, кейс клиента, уникальный взгляд
5. Мягкий CTA — приглашение к диалогу без давления, но с чётким триггером

ПРАВИЛА:
- Короткие абзацы (1-3 строки)
- Пустые строки между блоками для читабельности
- Максимум 1-2 эмодзи
- Заканчивай мягким, но чётким конверсионным триггером

ВАЖНО: Весь текст пиши ТОЛЬКО на русском языке. Никакого английского.

Верни ТОЛЬКО этот JSON:
{
  "structure": [
    "текст хука",
    "текст проблемы",
    "текст глубокой ценности",
    "текст позиционирования",
    "текст мягкого CTA"
  ],
  "cta": "финальный конверсионный призыв к действию"
}`
}
