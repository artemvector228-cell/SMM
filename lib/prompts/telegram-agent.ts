import { GenerateInput } from '@/lib/validations'

export function buildTelegramPrompt(input: GenerateInput): string {
  const goalMap: Record<string, string> = {
    dm: 'написать в личку (дать конкретное ключевое слово)',
    telegram: 'подписаться на основной канал',
    call: 'записаться на звонок/разбор',
    landing: 'перейти на сайт по ссылке',
  }

  const toneMap: Record<string, string> = {
    aggressive: 'агрессивный, жёсткий — режет правду без прикрас',
    authoritative: 'авторитетный — говорит как признанный эксперт, опирается на цифры и кейсы',
    empathetic: 'эмпатичный — близкий, как разговор с умным другом',
    bold: 'смелый — нарушает правила жанра, говорит то, что другие боятся',
    professional: 'профессиональный — структура, конкретика, без лишних слов',
  }

  const voiceLine = input.brand_voice
    ? `ГОЛОС БРЕНДА (точно соблюдай): ${input.brand_voice}`
    : `ТОН: ${toneMap[input.tone]}`

  return `Ты — стратегический копирайтер для Telegram-каналов с фокусом на продажи. Telegram читают вдумчиво — здесь строят авторитет и ведут к решению.

═══ БРИФ ═══
Ниша / продукт: ${input.niche}
Оффер: ${input.offer}
Аудитория: ${input.audience}
Боли: ${input.pain_points}
${voiceLine}
Целевое действие: ${goalMap[input.conversion_goal]}

═══ АРХИТЕКТУРА (5 блоков, каждый = отдельный абзац) ═══

БЛОК 1 — ХУК: Останавливает. Цифра+факт, парадокс или острый вопрос. 1-2 строки.
БЛОК 2 — ПРОБЛЕМА: Конкретный сценарий боли. Читатель видит себя. 2-4 строки.
БЛОК 3 — ГЛУБОКАЯ ЦЕННОСТЬ: Экспертный инсайт + конкретный механизм + результат. 4-6 строк.
БЛОК 4 — ПОЗИЦИОНИРОВАНИЕ: Почему именно этот продукт/эксперт. Один сильный факт. 2-3 строки.
БЛОК 5 — МЯГКИЙ CTA: Конкретный следующий шаг, снижает барьер входа. 1-2 строки.

═══ ПРАВИЛА ═══
✅ Между блоками — пустая строка
✅ Предложения до 15 слов
✅ 1-2 эмодзи максимум
✅ 180-280 слов итого
❌ "Многие предприниматели...", "В современном мире...", расплывчатые обещания
❌ Более 2 эмодзи
❌ Английские слова без необходимости

СТРОГО НА РУССКОМ ЯЗЫКЕ.

Верни ТОЛЬКО JSON:
{
  "structure": [
    "хук — 1-2 строки стоп-контента",
    "проблема — конкретный сценарий боли",
    "глубокая ценность — инсайт + механизм + результат",
    "позиционирование — доказательство экспертности",
    "мягкий CTA — конкретный следующий шаг"
  ],
  "cta": "финальное действие с ключевым словом или ссылкой"
}`
}
