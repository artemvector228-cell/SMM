import { GenerateInput } from '@/lib/validations'

export function buildCTAPrompt(input: GenerateInput): string {
  const goalMap = {
    dm: 'Личное сообщение (Direct) в Instagram или Telegram',
    telegram: 'Подписка на Telegram-канал или чат',
    call: 'Запись на звонок или консультацию',
    landing: 'Переход на лендинг по ссылке',
  }

  return `Ты — архитектор стратегии конверсии. Ты анализируешь оффер и создаёшь полный психологический блюпринт конверсии.

КОНТЕКСТ:
- Ниша: ${input.niche}
- Оффер: ${input.offer}
- Целевая аудитория: ${input.audience}
- Ключевые боли: ${input.pain_points}
- Цель конверсии: ${goalMap[input.conversion_goal]}

РАЗРАБОТАЙ СТРАТЕГИЮ КОНВЕРСИИ:

1. ГЛАВНЫЙ ТРИГГЕР: Самый мощный эмоциональный рычаг для этой конкретной аудитории (страх потери, жажда статуса, фрустрация от текущей ситуации и т.д.)

2. ПСИХОЛОГИЧЕСКИЕ РЫЧАГИ: 3-4 конкретных психологических принципа, которые работают для этой аудитории и оффера (авторитет, дефицит, социальное доказательство, взаимность и т.д.) — будь конкретен, а не обобщён

3. МЕХАНИЗМ CTA: Точная фраза принудительного действия с ключевым словом для достижения цели «${goalMap[input.conversion_goal]}»

ПРАВИЛА:
- Будь конкретен для ЭТОЙ ниши и аудитории — никаких шаблонных советов
- Ключевое слово CTA должно быть простым (1 слово: ПЛАН, АУДИТ, РОСТ, МАСШТАБ и т.д.)
- Главный триггер должен называть точную эмоцию, а не категорию

ВАЖНО: Весь текст пиши ТОЛЬКО на русском языке. Никакого английского.

Верни ТОЛЬКО этот JSON:
{
  "primary_trigger": "конкретный эмоциональный триггер для этой аудитории",
  "psychological_levers": ["рычаг 1", "рычаг 2", "рычаг 3", "рычаг 4"],
  "cta_mechanism": "точная фраза CTA с ключевым словом"
}`
}
